object LocalizationManager {
    private const val PREFS_NAME = "openpos_prefs"
    private const val KEY_LANG = "selected_language"

    // ברירת מחדל: אנגלית (ENGLISH) כפי שביקש המשתמש!
    private val _currentLanguage = MutableStateFlow(AppLanguage.ENGLISH)
    val currentLanguage: StateFlow<AppLanguage> = _currentLanguage.asStateFlow()

    fun init(context: Context) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val savedCode = prefs.getString(KEY_LANG, AppLanguage.ENGLISH.code) ?: AppLanguage.ENGLISH.code
        _currentLanguage.value = AppLanguage.entries.find { it.code == savedCode } ?: AppLanguage.ENGLISH
    }

    fun setLanguage(context: Context?, language: AppLanguage) {
        _currentLanguage.value = language
        context?.let {
            it.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
                .edit()
                .putString(KEY_LANG, language.code)
                .apply()
        }
    }

    fun getStrings(language: AppLanguage): PosStrings {
        return when (language) {
            AppLanguage.ENGLISH -> EnglishStrings
            AppLanguage.HEBREW -> HebrewStrings
            AppLanguage.SPANISH -> SpanishStrings
            AppLanguage.ARABIC -> HebrewStrings // תומך RTL
        }
    }
}
